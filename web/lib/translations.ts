const normalized = (text: string) => text.normalize("NFC").replace(/\s+/g, " ").trim();
const words = new Map(Object.entries(thai).map(([source, target]) => [normalized(source), target]));
const foldedWords = new Map(Array.from(words, ([source, target]) => [source.toLowerCase(), target]));
const escapePattern = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const patterns = Object.entries(thai).filter(([source]) => /\{\d+\}/.test(source)).map(([source, target]) => {
  const positions: string[] = [];
  const parts = normalized(source).split(/(\{\d+\})/);
  const expression = parts.map(part => {
    if (/^\{\d+\}$/.test(part)) { positions.push(part); return "(.*?)"; }
    return escapePattern(part).replace(/ /g, "\\s+");
  }).join("");
  return { expression: new RegExp(`^${expression}$`, "iu"), positions, target, specificity: source.replace(/\{\d+\}/g, "").length };
}).sort((a, b) => b.specificity - a.specificity);

export function translateText(source: string, language: Language): string {
  if (language === "en" || !source.trim()) return source;
  const text = normalized(source);
  let translated = words.get(text) ?? foldedWords.get(text.toLowerCase());
  if (!translated) {
    for (const pattern of patterns) {
      const match = pattern.expression.exec(source.trim());
      if (!match) continue;
      translated = pattern.target.replace(/\{\d+\}/g, key => match[pattern.positions.indexOf(key) + 1] ?? key);
      break;
    }
  }
  // shortcut: new server messages retain their original wording until added to this catalogue.
  if (!translated) return source;
  return source.slice(0, source.length - source.trimStart().length) + translated + source.slice(source.trimEnd().length);
}
